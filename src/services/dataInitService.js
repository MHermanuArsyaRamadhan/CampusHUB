import { get, set, STORAGE_KEYS } from './storageService';
import {
  DEMO_ACCOUNTS, DEMO_ORGANIZATIONS, DEMO_SCHEDULES,
  DEMO_NOTIFICATIONS, DEMO_REGISTRATIONS, DEMO_FAVORITES, DEMO_APPROVAL_HISTORY
} from '../data/seedData';

export const initializeData = () => {
  const initialized = get(STORAGE_KEYS.INITIALIZED);
  if (!initialized) {
    set(STORAGE_KEYS.USERS, DEMO_ACCOUNTS);
    set(STORAGE_KEYS.ORGANIZATIONS, DEMO_ORGANIZATIONS);
    set(STORAGE_KEYS.SCHEDULES, DEMO_SCHEDULES);
    set(STORAGE_KEYS.NOTIFICATIONS, DEMO_NOTIFICATIONS);
    set(STORAGE_KEYS.REGISTRATIONS, DEMO_REGISTRATIONS);
    set(STORAGE_KEYS.FAVORITES, DEMO_FAVORITES);
    set(STORAGE_KEYS.APPROVAL_HISTORY, DEMO_APPROVAL_HISTORY);
    set(STORAGE_KEYS.INITIALIZED, true);
  }
};

export const resetData = () => {
  set(STORAGE_KEYS.USERS, DEMO_ACCOUNTS);
  set(STORAGE_KEYS.ORGANIZATIONS, DEMO_ORGANIZATIONS);
  set(STORAGE_KEYS.SCHEDULES, DEMO_SCHEDULES);
  set(STORAGE_KEYS.NOTIFICATIONS, DEMO_NOTIFICATIONS);
  set(STORAGE_KEYS.REGISTRATIONS, DEMO_REGISTRATIONS);
  set(STORAGE_KEYS.FAVORITES, DEMO_FAVORITES);
  set(STORAGE_KEYS.APPROVAL_HISTORY, DEMO_APPROVAL_HISTORY);
  set(STORAGE_KEYS.INITIALIZED, true);
  // Keep current user session
};

